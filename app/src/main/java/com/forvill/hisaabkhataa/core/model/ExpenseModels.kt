package com.forvill.hisaabkhataa.core.model

enum class ExpenseType {
    Income,
    Expense
}

data class ExpenseCategory(
    val id: String,
    val name: String,
    val icon: String, // String representation of an icon or a resource name
    val color: Long // Hex color value
)

data class TransactionExpense(
    val id: String,
    val amount: Int,
    val note: String,
    val categoryId: String,
    val type: ExpenseType,
    val timestamp: Long,
    val merchant: String? = null,
    val isAutoGenerated: Boolean = false
)

data class ExpenseSummary(
    val totalIncome: Int,
    val totalExpense: Int,
    val netSavings: Int,
    val categoryWiseSpending: Map<String, Int>
)
