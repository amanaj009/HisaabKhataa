package com.forvill.hisaabkhataa.core.sms

import com.forvill.hisaabkhataa.core.model.ExpenseType
import com.forvill.hisaabkhataa.core.model.TransactionExpense
import java.util.UUID
import java.util.regex.Pattern

object SmsTransactionScanner {

    private val amountPattern = Pattern.compile("(?i)(?:rs|inr|amt)\\.?\\s*([\\d,]+\\.?\\d*)")
    private val debitKeywords = listOf("debited", "spent", "paid", "sent", "transaction at")
    private val creditKeywords = listOf("credited", "received", "added")

    fun scanMessage(body: String, timestamp: Long): TransactionExpense? {
        val cleanBody = body.lowercase()
        
        // Ignore OTPs and non-transactional messages
        if (cleanBody.contains("otp") || cleanBody.contains("verification code")) return null
        
        val amountMatch = amountPattern.matcher(body)
        if (!amountMatch.find()) return null
        
        val amountStr = amountMatch.group(1)?.replace(",", "") ?: return null
        val amount = amountStr.toDoubleOrNull()?.toInt() ?: return null

        val type = when {
            debitKeywords.any { cleanBody.contains(it) } -> ExpenseType.Expense
            creditKeywords.any { cleanBody.contains(it) } -> ExpenseType.Income
            else -> return null
        }

        val merchant = detectMerchant(cleanBody)
        val categoryId = if (type == ExpenseType.Income) "income" else detectCategory(merchant, cleanBody)

        return TransactionExpense(
            id = UUID.randomUUID().toString(),
            amount = amount,
            note = merchant ?: "Auto-detected transaction",
            categoryId = categoryId,
            type = type,
            timestamp = timestamp,
            merchant = merchant,
            isAutoGenerated = true
        )
    }

    private fun detectMerchant(body: String): String? {
        val merchants = listOf("swiggy", "zomato", "amazon", "flipkart", "uber", "ola", "petrol", "electricity", "jio", "airtel", "netflix")
        return merchants.find { body.contains(it) }?.replaceFirstChar { it.uppercase() }
    }

    private fun detectCategory(merchant: String?, body: String): String {
        val m = merchant?.lowercase() ?: ""
        return when {
            m.contains("swiggy") || m.contains("zomato") || body.contains("restaurant") -> "food"
            m.contains("amazon") || m.contains("flipkart") || body.contains("shopping") -> "shopping"
            m.contains("petrol") || m.contains("fuel") -> "fuel"
            body.contains("bill") || body.contains("electricity") || body.contains("water") -> "bills"
            body.contains("recharge") || m.contains("jio") || m.contains("airtel") -> "mobile"
            body.contains("salary") -> "salary"
            body.contains("interest") -> "interest"
            else -> "others"
        }
    }
}
